"""Positioning reference signals (PRS) of an LTE cell, and the RSTD a UE measures from them. [spec] unless marked [design]

What is here: the PRS sequence and its mapping to resource elements as TS 36.211 V19.3.0 clauses 6.10.4.1 and 6.10.4.2 define them (without
PRS frequency hopping), an OFDM waveform of one PRS subframe, and a ToA estimator that correlates a received waveform with a cell's own PRS.
What is not here: the PRS is not generated by rt-mbms-tx nor measured by rt-mbms-modem; this module is the signal processing a measuring UE
would do, run on a simulated channel, so that the RSTDs fed to the positioning chain come from waveforms and not from a formula.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

from .timebase import prs_period_offset

# Clause 7.2: Nc = 1600. [spec]
_NC = 1600
# FFT size for a downlink bandwidth in resource blocks. [design: the usual LTE numerology, sample rate = 15 kHz * FFT size]
_FFT_FOR_RB = {6: 128, 15: 256, 25: 512, 50: 1024, 75: 1536, 100: 2048}


def gold_sequence(c_init: int, length: int) -> np.ndarray:
    """Clause 7.2: c(n) = (x1(n + Nc) + x2(n + Nc)) mod 2, x1(n + 31) = (x1(n + 3) + x1(n)) mod 2,
    x2(n + 31) = (x2(n + 3) + x2(n + 2) + x2(n + 1) + x2(n)) mod 2, x1(0) = 1, x1(n) = 0 for n = 1..30, and
    c_init = sum of x2(i) * 2^i for i = 0..30."""
    total = _NC + length + 31
    x1 = [0] * total
    x2 = [0] * total
    x1[0] = 1
    for i in range(31):
        x2[i] = (c_init >> i) & 1
    for n in range(total - 31):
        x1[n + 31] = (x1[n + 3] + x1[n]) & 1
        x2[n + 31] = (x2[n + 3] + x2[n + 2] + x2[n + 1] + x2[n]) & 1
    return np.array([(x1[n + _NC] + x2[n + _NC]) & 1 for n in range(length)], dtype=np.uint8)


def prs_c_init(n_id_prs: int, n_s: int, l: int, normal_cp: bool = True) -> int:
    """Clause 6.10.4.1: c_init = 2^28 * floor(N_ID^PRS / 512) + 2^10 * (7 * (n_s + 1) + l + 1) * (2 * (N_ID^PRS mod 512) + 1)
    + 2 * (N_ID^PRS mod 512) + N_CP, with N_CP = 1 for normal CP and 0 for extended CP, N_ID^PRS in 0..4095."""
    if not 0 <= n_id_prs <= 4095:
        raise ValueError("N_ID^PRS must be 0..4095")
    return (2**28 * (n_id_prs // 512) + 2**10 * (7 * (n_s + 1) + l + 1) * (2 * (n_id_prs % 512) + 1)
            + 2 * (n_id_prs % 512) + (1 if normal_cp else 0))


def prs_sequence(n_id_prs: int, n_s: int, l: int, normal_cp: bool = True, n_rb_max_dl: int = 110) -> np.ndarray:
    """Clause 6.10.4.1: r(m) = 1/sqrt(2) * (1 - 2 c(2m)) + j * 1/sqrt(2) * (1 - 2 c(2m + 1)), m = 0 .. 2 N_RB^max,DL - 1."""
    c = gold_sequence(prs_c_init(n_id_prs, n_s, l, normal_cp), 4 * n_rb_max_dl).astype(float)
    return ((1 - 2 * c[0::2]) + 1j * (1 - 2 * c[1::2])) / math.sqrt(2)


def prs_symbols(normal_cp: bool, n_s: int, four_pbch_ports: bool) -> list[int]:
    """The OFDM symbols of a slot that carry PRS (clause 6.10.4.2, port 6)."""
    if normal_cp:
        return [3, 5, 6] if n_s % 2 == 0 else ([2, 3, 5, 6] if four_pbch_ports else [1, 2, 3, 5, 6])
    return [4, 5] if n_s % 2 == 0 else ([2, 4, 5] if four_pbch_ports else [1, 2, 4, 5])


def sync_pbch_core_mask(n_s: int, n_rb_dl: int, normal_cp: bool = True, n_f: int = 0) -> np.ndarray:
    """Resource elements of one slot that carry the PSS, SSS or the core set of the PBCH of an MBMS-dedicated cell (5G Broadcast), as a
    boolean grid [subcarrier, symbol]. `n_s` is the slot number in the radio frame and `n_f` the radio frame number.

    PSS: n = 0..61, k = n - 31 + N_RB^DL N_sc^RB / 2, in slot 0 of the frames with n_f mod 4 = 0 only (clause 6.11.1.2); there is none in
    slot 10. SSS: the same k, in OFDM symbol N_symb^DL - 2 of the slots where the PSS is transmitted (clause 6.11.2.2). PBCH core set:
    k = N_RB^DL N_sc^RB / 2 - 36 + k', k' = 0..71, l = 0..3 in slot 1, in the frames with n_f mod 4 = 0 (clause 6.6.4). The reserved
    resource elements next to the PSS and SSS (n = -5..-1 and 62..66) are not included: they carry no signal. PBCH repetition and CAS
    muting (clause 6.6.4) are not modelled.
    """
    n_sym = 7 if normal_cp else 6
    mask = np.zeros((12 * n_rb_dl, n_sym), dtype=bool)
    centre = 6 * n_rb_dl
    if n_f % 4 == 0:
        if n_s == 0:
            mask[centre - 31: centre + 31, n_sym - 1] = True   # PSS
            mask[centre - 31: centre + 31, n_sym - 2] = True   # SSS
        if n_s == 1:
            mask[centre - 36: centre + 36, 0:4] = True         # PBCH core set
    return mask


def prs_slot_grid(n_id_prs: int, n_s: int, n_rb_dl: int, n_rb_prs: int | None = None, normal_cp: bool = True,
                  four_pbch_ports: bool = False, n_rb_max_dl: int = 110, n_f: int = 0) -> np.ndarray:
    """Clause 6.10.4.2 without frequency hopping: a[k, l] = r_{l, n_s}(m') for the PRS resource elements, zero elsewhere.

    k = 6 (m + N_RB^DL - N_RB^PRS) + ((6 - l + v_shift) mod 6) for normal CP, with 5 in place of 6 in the shift for extended CP;
    m = 0 .. 2 N_RB^PRS - 1; m' = m + N_RB^max,DL - N_RB^PRS; v_shift = N_ID^PRS mod 6.
    Resource elements of the PSS, SSS and PBCH core set (`sync_pbch_core_mask`, the pattern of an MBMS-dedicated cell in radio frame
    `n_f`) are left empty, as clause 6.10.4 requires. The PBCH, PSS and SSS themselves are not generated.
    """
    n_rb_prs = n_rb_dl if n_rb_prs is None else n_rb_prs
    if not 0 < n_rb_prs <= n_rb_dl <= n_rb_max_dl:
        raise ValueError("need 0 < N_RB^PRS <= N_RB^DL <= N_RB^max,DL")
    n_sym = 7 if normal_cp else 6
    grid = np.zeros((12 * n_rb_dl, n_sym), dtype=complex)
    v_shift = n_id_prs % 6
    base = 6 if normal_cp else 5
    m = np.arange(2 * n_rb_prs)
    for l in prs_symbols(normal_cp, n_s, four_pbch_ports):
        r = prs_sequence(n_id_prs, n_s, l, normal_cp, n_rb_max_dl)
        k = 6 * (m + n_rb_dl - n_rb_prs) + ((base - l + v_shift) % 6)
        grid[k, l] = r[m + n_rb_max_dl - n_rb_prs]
    grid[sync_pbch_core_mask(n_s, n_rb_dl, normal_cp, n_f)] = 0   # clause 6.10.4: PRS is not mapped onto those resource elements
    return grid


def _cp_lengths(n_fft: int) -> tuple[int, int]:
    """Normal cyclic prefix in samples: 160 for the first symbol of a slot and 144 for the others at 2048-point FFT, scaled."""
    return 160 * n_fft // 2048, 144 * n_fft // 2048


def ofdm_subframe(grids: list[np.ndarray], n_rb_dl: int) -> np.ndarray:
    """[design] Time-domain waveform of one subframe (two slots, normal CP) from the resource grids of its two slots. DC is not used."""
    n_fft = _FFT_FOR_RB[n_rb_dl]
    cp0, cp = _cp_lengths(n_fft)
    out = []
    for grid in grids:
        for l in range(7):
            spec = np.zeros(n_fft, dtype=complex)
            k_rel = np.arange(12 * n_rb_dl) - 6 * n_rb_dl
            bins = np.where(k_rel < 0, n_fft + k_rel, k_rel + 1)
            spec[bins] = grid[:, l]
            sym = np.fft.ifft(spec) * math.sqrt(n_fft)
            pre = cp0 if l == 0 else cp
            out.append(np.concatenate([sym[-pre:], sym]))
    return np.concatenate(out)


def prs_subframe(n_id_prs: int, subframe: int, n_rb_dl: int, n_rb_prs: int | None = None, n_f: int = 0) -> np.ndarray:
    """Waveform of the PRS of one subframe of radio frame `n_f` (slots 2 * subframe and 2 * subframe + 1)."""
    grids = [prs_slot_grid(n_id_prs, 2 * subframe + s, n_rb_dl, n_rb_prs, n_f=n_f) for s in (0, 1)]
    return ofdm_subframe(grids, n_rb_dl)


def sample_rate_hz(n_rb_dl: int) -> float:
    if n_rb_dl not in _FFT_FOR_RB:
        raise ValueError(f"N_RB^DL {n_rb_dl} is not one of {sorted(_FFT_FOR_RB)}")
    return 15000.0 * _FFT_FOR_RB[n_rb_dl]


def correlation_lag(rx: np.ndarray, ref: np.ndarray, upsample: int = 16) -> float:
    """[design] Position, in samples and with sub-sample resolution, of the strongest match of `ref` inside `rx`.

    The correlation is done in the frequency domain and zero-padded there to `upsample` times the resolution; the peak is taken on that
    grid and refined by a parabola. Lags run from 0 to len(rx) - len(ref)."""
    n = 1 << int(math.ceil(math.log2(len(rx) + len(ref))))
    spec = np.fft.fft(rx, n) * np.conj(np.fft.fft(ref, n))
    padded = np.zeros(n * upsample, dtype=complex)
    half = n // 2
    padded[:half] = spec[:half]
    padded[-half:] = spec[half:]
    corr = np.abs(np.fft.ifft(padded))
    last = (len(rx) - len(ref)) * upsample
    peak = int(np.argmax(corr[: last + 1]))
    # parabola through the peak and its two neighbours, for the position between grid points
    frac = 0.0
    if 0 < peak < last:
        a, b, c = corr[peak - 1], corr[peak], corr[peak + 1]
        denom = a - 2 * b + c
        if denom != 0:
            frac = 0.5 * (a - c) / denom
    return (peak + frac) / upsample


@dataclass(frozen=True)
class PrsCell:
    """A cell as the measuring UE sees it. `delay_s` is the arrival delay of the cell's subframe grid against the UE's own subframe
    grid (the reference cell's): propagation delay plus the cell's transmit offset, with the offset folded to the subframe "closest
    in time" as TS 36.214 V19.0.0 clause 5.1.12 defines the RSTD. `power_db` is the received power against the reference cell."""
    n_id_prs: int
    i_prs: int
    delay_s: float
    power_db: float = 0.0


def occasion_subframe(i_prs: int) -> int:
    """Subframe number (0..9) of the first PRS occasion, from Delta_PRS (Table 6.10.4.3-1) and the instance condition of clause 6.10.4.3."""
    _, delta = prs_period_offset(i_prs)
    return delta % 10


def measure_rstd(cells: list[PrsCell], n_rb_dl: int, snr_db: float, rng: np.random.Generator,
                 window_ms: float = 3.0, n_f: int = 0) -> list[float]:
    """[design] RSTDs, in seconds, of cells 1..N against cell 0, estimated from simulated received waveforms.

    Cells whose first occasion falls in the same subframe share one received window, so they interfere with each other as they
    would on air; cells in different subframes are received in separate windows (the UE reads each cell's subframe, then takes the
    difference to the reference cell's, as clause 5.1.12 defines the RSTD). Within a window the reference cell's nominal subframe
    start is 1 ms in; a cell's arrival is its `delay_s` after that, so delays from -1 ms to the window length less 2 ms (+1 ms for the default) fit; others are refused.

    `n_f` is the radio frame of the occasion; it decides which resource elements the PSS, SSS and PBCH take from the PRS
    (`sync_pbch_core_mask`).

    `snr_db` is the signal to noise ratio per sample of a cell at `power_db` = 0 while its subframe is present. The channel is one path
    per cell and white Gaussian noise: no multipath, no frequency offset, no tracking of first-arriving paths.
    """
    if n_rb_dl not in _FFT_FOR_RB:
        raise ValueError(f"N_RB^DL {n_rb_dl} is not one of {sorted(_FFT_FOR_RB)}")
    if len(cells) < 2:
        raise ValueError("an RSTD needs a reference cell and at least one other")
    fs = sample_rate_hz(n_rb_dl)
    n_win = int(round(window_ms * 1e-3 * fs))
    # the reference subframe starts 1 ms into the window and lasts 1 ms: a delay beyond what fits would wrap round in the FFT shift
    room_s = (window_ms - 2.0) * 1e-3
    for c in cells:
        if not -1e-3 <= c.delay_s <= room_s:
            raise ValueError(f"delay {c.delay_s * 1e6:.1f} us is outside the window (-1000 .. {room_s * 1e6:.0f} us)")
    freqs = np.fft.fftfreq(n_win, d=1 / fs)
    refs = [prs_subframe(c.n_id_prs, occasion_subframe(c.i_prs), n_rb_dl, n_f=n_f) for c in cells]
    unit_power = float(np.mean(np.abs(refs[0]) ** 2))
    sigma = math.sqrt(unit_power / 10 ** (snr_db / 10) / 2)
    windows: dict[int, np.ndarray] = {}
    for c, ref in zip(cells, refs):
        sf = occasion_subframe(c.i_prs)
        rx = windows.setdefault(sf, np.zeros(n_win, dtype=complex))
        padded = np.zeros(n_win, dtype=complex)
        padded[: len(ref)] = ref * 10 ** (c.power_db / 20)
        rx += np.fft.ifft(np.fft.fft(padded) * np.exp(-2j * np.pi * freqs * (1e-3 + c.delay_s)))
    for sf in windows:
        windows[sf] = windows[sf] + sigma * (rng.standard_normal(n_win) + 1j * rng.standard_normal(n_win))
    toa = [correlation_lag(windows[occasion_subframe(c.i_prs)], ref) / fs - 1e-3 for c, ref in zip(cells, refs)]
    return [toa[i] - toa[0] for i in range(1, len(cells))]


